import { fireEvent, render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';
import { IncrementalConfirmationDemo } from './IncrementalConfirmationDemo';
import { ConceptGraphView } from './ConceptGraphView';
import { REUSED_ITEM_RESULT } from './experimentGraph.fixture';

const summary = () => screen.getByLabelText('本次演示统计');
const openDemo = (user: ReturnType<typeof userEvent.setup>) => user.click(screen.getByRole('button', { name: '增量确认演示（实验）' }));

describe('合成增量确认演示', () => {
  it('未选择不改变数据；归入、待定和撤销在案例之间保留且不重复', async () => {
    const user = userEvent.setup();
    render(<IncrementalConfirmationDemo onClose={() => {}} />);
    expect(summary()).toHaveTextContent('新增 0 个概念、0 条条目');
    expect(screen.getByRole('dialog')).toHaveTextContent('关闭或刷新即清空');
    expect(screen.getByRole('region', { name: '新增条目与原文' })).toHaveTextContent('合成笔记 A');
    await user.dblClick(screen.getByRole('button', { name: '归到这里' }));
    expect(summary()).toHaveTextContent('新增 0 个概念、1 条条目');
    expect(screen.getByRole('status')).toHaveTextContent('旧条目未改动');
    await user.click(screen.getByRole('button', { name: /3\. 检查 grad/ }));
    await user.click(screen.getByRole('button', { name: '暂不决定' }));
    expect(summary()).toHaveTextContent('待定 1 条');
    expect(summary()).toHaveTextContent('新增 0 个概念、1 条条目');
    await user.click(screen.getByRole('button', { name: '撤销本条选择' }));
    await user.click(screen.getByRole('button', { name: /1\. 反向传播/ }));
    await user.click(screen.getByRole('button', { name: '撤销本条选择' }));
    expect(summary()).toHaveTextContent('新增 0 个概念、0 条条目');
  });
  it('另建需填写名称和语境，取消不提交，确认可撤销且旧内容不变', async () => {
    const user = userEvent.setup();
    render(<IncrementalConfirmationDemo onClose={() => {}} />);
    await user.click(screen.getByRole('button', { name: /2\. x.grad/ }));
    const oldContent = screen.getByRole('region', { name: '已有概念与内容' }).textContent;
    expect(screen.getByRole('region', { name: '演示意见' })).toHaveTextContent('非原文');
    await user.click(screen.getByRole('button', { name: '另建' }));
    await user.clear(screen.getByLabelText('新概念名称'));
    expect(screen.getByRole('button', { name: '确认另建（仅演示）' })).toBeDisabled();
    await user.click(screen.getByRole('button', { name: '取消另建' }));
    expect(summary()).toHaveTextContent('新增 0 个概念、0 条条目');
    await user.click(screen.getByRole('button', { name: '另建' }));
    await user.clear(screen.getByLabelText('语境说明'));
    expect(screen.getByRole('button', { name: '确认另建（仅演示）' })).toBeDisabled();
    await user.type(screen.getByLabelText('语境说明'), '框架中的梯度存储操作');
    await user.click(screen.getByRole('button', { name: '确认另建（仅演示）' }));
    expect(summary()).toHaveTextContent('新增 1 个概念、1 条条目');
    expect(screen.getByRole('region', { name: '已有概念与内容' }).textContent).toBe(oldContent);
    await user.click(screen.getByRole('button', { name: '撤销本条选择' }));
    expect(summary()).toHaveTextContent('新增 0 个概念、0 条条目');
  });
  it('键盘可提交；所有决定和撤销不调用网络或浏览器持久化', async () => {
    const user = userEvent.setup();
    const request = vi.spyOn(globalThis, 'fetch');
    const write = vi.spyOn(Storage.prototype, 'setItem');
    const remove = vi.spyOn(Storage.prototype, 'removeItem');
    render(<IncrementalConfirmationDemo onClose={() => {}} />);
    request.mockClear(); write.mockClear(); remove.mockClear();
    screen.getByRole('button', { name: '归到这里' }).focus();
    await user.keyboard('{Enter}');
    expect(summary()).toHaveTextContent('新增 0 个概念、1 条条目');
    await user.click(screen.getByRole('button', { name: '撤销本条选择' }));
    await user.click(screen.getByRole('button', { name: '暂不决定' }));
    await user.click(screen.getByRole('button', { name: /2\. x.grad/ }));
    await user.click(screen.getByRole('button', { name: '另建' }));
    await user.click(screen.getByRole('button', { name: '确认另建（仅演示）' }));
    expect(request).not.toHaveBeenCalled();
    expect(write).not.toHaveBeenCalled();
    expect(remove).not.toHaveBeenCalled();
  });
  it('取消另建后焦点仍在弹窗内，直接 Escape 可关闭', async () => {
    const user = userEvent.setup(); const close = vi.fn();
    render(<IncrementalConfirmationDemo onClose={close} />);
    await user.click(screen.getByRole('button', { name: '另建' }));
    await user.click(screen.getByRole('button', { name: '取消另建' }));
    expect(screen.getByRole('status')).toHaveFocus();
    await user.keyboard('{Escape}');
    expect(close).toHaveBeenCalledOnce();
  });
  it('关闭回调与键盘 Escape 可用', async () => {
    const user = userEvent.setup(); const close = vi.fn();
    render(<IncrementalConfirmationDemo onClose={close} />);
    await user.keyboard('{Escape}');
    expect(close).toHaveBeenCalledOnce();
  });
  it('打开/关闭演示不替换导入图、图层或选中项，重开及重挂载清空演示', async () => {
    const user = userEvent.setup();
    const view = render(<ConceptGraphView />);
    const file = new File(['{}'], 'synthetic.json', { type: 'application/json' });
    Object.defineProperty(file, 'text', { value: async () => JSON.stringify(REUSED_ITEM_RESULT) });
    fireEvent.change(screen.getByLabelText('选择实验结果文件'), { target: { files: [file] } });
    await screen.findByRole('button', { name: '回到示例' });
    await user.click(screen.getByRole('button', { name: /^梯度，/ }));
    const graph = screen.getByRole('group', { name: '概念图' }).innerHTML;
    const details = screen.getByRole('region', { name: '详情' }).textContent;
    await openDemo(user);
    await user.click(screen.getByRole('button', { name: '归到这里' }));
    await user.keyboard('{Escape}');
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
    expect(screen.getByRole('group', { name: '概念图' }).innerHTML).toBe(graph);
    expect(screen.getByRole('region', { name: '详情' }).textContent).toBe(details);
    expect(screen.getByRole('button', { name: '回到示例' })).toBeInTheDocument();
    await openDemo(user);
    expect(summary()).toHaveTextContent('新增 0 个概念、0 条条目');
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: '关闭并清空演示' }));
    view.unmount();
    render(<ConceptGraphView />);
    await openDemo(user);
    expect(summary()).toHaveTextContent('新增 0 个概念、0 条条目');
  });
});
